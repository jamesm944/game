/**
 * Bug-replay → golden-fixture converter core — SPEC §2.12 / M5-T3
 * (issue #65).
 *
 * A user-attached `.ageofreplay` becomes a permanent, bisectable
 * regression fixture: {@link buildGoldenFixtureFiles} validates the
 * artifact and emits the two files of a `tests/golden/<name>/` directory
 * —
 *
 * - `case.json`: the replay verbatim (golden-fixture shape), and
 * - `golden.test.ts`: a generated harness that replays the skirmish
 *   headlessly through the REAL production bootstrap and fails at the
 *   FIRST diverging milestone with the loud expected-vs-actual desync
 *   report.
 *
 * While the bug exists the fixture is red at that simulated second; a
 * `git bisect` over it lands on the exact offending commit. Regen after
 * an intentional sim change: re-export the match and re-run
 * `npm run replay:to-fixture <file> <name>` (snapshot-based sibling
 * fixtures regenerate with `npm run golden:record`).
 */

import { parseReplay, ReplayFormatError } from "../sim/replay/play";
import type { ReplayArtifact } from "../sim/replay/record";

/** Fixture directory names are repo-safe slugs (m4t6c, my-bug-123…). */
export const FIXTURE_NAME_PATTERN = /^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/;

export function isValidFixtureName(name: string): boolean {
  return name.length <= 48 && FIXTURE_NAME_PATTERN.test(name);
}

/** The two files a converted fixture directory contains. */
export interface GoldenFixtureFiles {
  readonly caseJson: string;
  readonly goldenTestTs: string;
}

/**
 * Validate `raw` as a replay artifact under fixture `name` and build
 * the fixture files. Throws {@link ReplayFormatError} on malformed
 * input or a bad name — garbage never becomes a fixture.
 */
export function buildGoldenFixtureFiles(
  raw: unknown,
  name: string,
): GoldenFixtureFiles {
  if (!isValidFixtureName(name)) {
    throw new ReplayFormatError(
      `fixture name ${JSON.stringify(name)} must be a lowercase slug (letters/digits/dashes, ≤48 chars)`,
    );
  }
  // Round-trip through the strict parser: only well-formed artifacts.
  const replay = parseReplay(raw);
  return {
    caseJson: `${JSON.stringify(replay, null, 2)}\n`,
    goldenTestTs: goldenTestSource(replay),
  };
}

function goldenTestSource(replay: ReplayArtifact): string {
  const commandCount = replay.commands.length;
  const milestoneCount = replay.milestones.length;
  return `/**
 * Generated golden bug-replay fixture — M5-T3 pipeline (SPEC §2.12).
 *
 * DO NOT EDIT BY HAND — generated by \`npm run replay:to-fixture\` from
 * a user-exported .ageofreplay (issue #65):
 *   seed ${String(replay.seed)} · ${String(replay.ticks)} ticks · ${String(commandCount)} commands · ${String(milestoneCount)} milestones
 *
 * The test replays the recorded skirmish headlessly through the real
 * production bootstrap and FAILS AT THE FIRST DIVERGING MILESTONE with
 * the expected-vs-actual desync report — git bisect over this file
 * lands on the commit that broke the recorded behavior.
 *
 * REGEN INSTRUCTIONS: after an INTENTIONAL sim change, re-export the
 * same match and re-run \`npm run replay:to-fixture <file> <name>\` to
 * refresh case.json. Snapshot-based sibling fixtures regenerate via
 * \`npm run golden:record\`.
 */
import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { runReplayHeadless } from "../../../src/game/replayPlayer";
import {
  formatReplayDesyncLines,
  parseReplay,
} from "../../../src/sim/replay/play";
import { installSimPurityShims } from "../../helpers/sim-purity-shims";

const replay = parseReplay(
  JSON.parse(readFileSync(new URL("./case.json", import.meta.url), "utf8")),
);

installSimPurityShims();

describe("golden bug-replay fixture", () => {
  it("replays the recorded skirmish byte-exact to every milestone", async () => {
    const result = await runReplayHeadless(replay);
    const divergence = result.divergence;
    if (divergence !== undefined) {
      throw new Error(formatReplayDesyncLines(divergence).join("\\n"));
    }
    expect(result.milestones).toEqual(replay.milestones);
  }, 240_000);
});
`;
}
